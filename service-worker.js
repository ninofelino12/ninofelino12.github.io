'use strict';

const CACHE_NAME = 'markas-repo-v2';
const APP_ROOT = self.registration.scope;
const APP_SHELL = [
  APP_ROOT,
  new URL('index.html', APP_ROOT).href,
  new URL('favorit.json', APP_ROOT).href,
  new URL('social.json', APP_ROOT).href,
  new URL('manifest.webmanifest', APP_ROOT).href,
  new URL('icons/icon-192.png', APP_ROOT).href,
  new URL('icons/icon-512.png', APP_ROOT).href
];
const OFFLINE_PAGE = new URL('index.html', APP_ROOT).href;

self.addEventListener('install', event => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then(cache => cache.addAll(APP_SHELL))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', event => {
  event.waitUntil(
    caches.keys()
      .then(keys => Promise.all(
        keys
          .filter(key => key.startsWith('markas-repo-') && key !== CACHE_NAME)
          .map(key => caches.delete(key))
      ))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  const isJsonData = [
    new URL('favorit.json', APP_ROOT).href,
    new URL('social.json', APP_ROOT).href
  ].includes(url.href);
  if (request.mode === 'navigate' || isJsonData) {
    event.respondWith(
      fetch(request).then(async response => {
          if (response.ok) {
            const cache = await caches.open(CACHE_NAME);
            await cache.put(request, response.clone());
          }
          return response;
        })
        .catch(async () => {
          const cached = await caches.match(request);
          if (cached) return cached;
          if (request.mode === 'navigate') return caches.match(OFFLINE_PAGE);
          return Response.error();
        })
    );
    return;
  }

  event.respondWith(
    caches.match(request).then(cached => {
      if (cached) return cached;
      return fetch(request).then(async response => {
        if (response.ok) {
          const cache = await caches.open(CACHE_NAME);
          await cache.put(request, response.clone());
        }
        return response;
      });
    })
  );
});
